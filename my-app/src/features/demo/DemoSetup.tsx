import type { StartAt } from '../../services/rooms'
import type { BallotSource, DemoMode, DemoView } from './demoModel'
import './DemoSetup.css'

type IconName = 'solo' | 'split' | 'independent' | 'cube' | 'tiles' | 'list' | 'sparkles' | 'play' | 'skip'
type Choice<Value extends string> = { value: Value; label: string; icon: IconName; description: string }

const MODES: Choice<DemoMode>[] = [
    { value: 'solo', label: 'Solo', icon: 'solo', description: 'Play as Alex with two automated board members.' },
]
const STAGES: Choice<DemoView>[] = [
    { value: '3d', label: '3D Boardroom', icon: 'cube', description: 'Take a seat at the boardroom table.' },
    { value: 'call', label: 'Call Tiles', icon: 'tiles', description: 'See participants in a call grid.' },
]
const BALLOTS: Choice<BallotSource>[] = [
    { value: 'authored', label: 'Prepared Choices', icon: 'list', description: 'Use the saved T01 choices and recorded decision guide.' },
    { value: 'ai', label: 'AI Generated', icon: 'sparkles', description: 'Use choices generated by Vertex agents.' },
]
const STARTS: Choice<StartAt>[] = [
    { value: 'beginning', label: 'Full Game', icon: 'play', description: 'Briefing, Round 1 decisions, Round 2 coaching, then the assessment.' },
    { value: 'assessment', label: 'Round 3 Test', icon: 'skip', description: 'Skip straight to the multiple choice assessment; Rounds 1 and 2 use the prerecorded answers.' },
]
const RECORDINGS = [
    { seat: 'Alex', topic: 'Leadership', text: 'Appointing an interim coordinator when the director is unavailable and no alternate is named.', seconds: '14.21' },
    { seat: 'Morgan', topic: 'Recovery', text: 'Checking backup usability, dependencies and a restoration estimate before promising recovery.', seconds: '17.18' },
    { seat: 'Sam', topic: 'Communications', text: 'Considering approved paper appointments and separating facts, unknowns and the next update.', seconds: '14.63' },
    { seat: 'Recorded decision guide', topic: 'Voting', text: 'Reads the fixed T01 choices when voting opens. It is labelled as recorded and never counts as a ballot.', seconds: '19.74' },
]

function ChoiceIcon({ name }: { name: IconName }) {
    return <svg aria-hidden="true" viewBox="0 0 32 32" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round">
        {name === 'solo' && <><circle cx="16" cy="10" r="5" /><path d="M6 28v-3a10 10 0 0 1 20 0v3M11 28h10" /></>}
        {name === 'split' && <><rect x="3" y="5" width="26" height="22" rx="3" /><path d="M12 5v22M21 5v22M3 10h26" /></>}
        {name === 'independent' && <><rect x="3" y="12" width="17" height="15" rx="2" /><path d="M10 8V6a2 2 0 0 1 2-2h15a2 2 0 0 1 2 2v12a2 2 0 0 1-2 2h-3M3 17h17M10 9h15" /></>}
        {name === 'cube' && <><path d="m16 3 12 7v13l-12 7-12-7V10zM4 10l12 7 12-7M16 17v13M10 6l12 7" /></>}
        {name === 'tiles' && <>{[[4, 4], [18, 4], [4, 18], [18, 18]].map(([x, y]) => <rect key={`${x}:${y}`} x={x} y={y} width="10" height="10" rx="2" />)}</>}
        {name === 'list' && <><rect x="6" y="3" width="21" height="26" rx="3" /><path d="M13 10h8M13 16h8M13 22h8M9 10h.1M9 16h.1M9 22h.1" /></>}
        {name === 'play' && <><circle cx="16" cy="16" r="13" /><path d="m13 10 9 6-9 6z" /></>}
        {name === 'skip' && <><path d="m5 8 9 8-9 8zM15 8l9 8-9 8zM27 8v16" /></>}
        {name === 'sparkles' && <><path d="m18 3 3.5 9.5L31 16l-9.5 3.5L18 29l-3.5-9.5L5 16l9.5-3.5zM5 2v6M2 5h6M5 24v6M2 27h6" /></>}
    </svg>
}

/** Native radio groups retain arrow key navigation and form selection semantics. */
function ChoiceGroup<Value extends string>({ name, title, value, choices, onChange, disabled }: { name: string; title: string; value: Value; choices: Choice<Value>[]; onChange: (value: Value) => void; disabled: boolean }) {
    return <fieldset className="demo-choice-group" disabled={disabled}>
        <legend>{title}</legend>
        <div className={`demo-choice-grid demo-choice-grid--${choices.length}`}>
            {choices.map((choice) => <label key={choice.value} className="demo-choice" title={choice.description}>
                <input type="radio" name={name} value={choice.value} checked={value === choice.value} onChange={() => onChange(choice.value)} aria-describedby={`${name}-${choice.value}-description`} />
                <span className="demo-choice-face"><span className="demo-choice-icon"><ChoiceIcon name={choice.icon} /></span><span className="demo-choice-label">{choice.label}</span><span className="demo-choice-mark" aria-hidden="true"><svg viewBox="0 0 16 16" fill="none" stroke="currentColor" strokeWidth="1.7"><path d="m4 8 3 3 5-6" /></svg></span></span>
                <span className="demo-setup-sr" id={`${name}-${choice.value}-description`}>{choice.description}</span>
            </label>)}
        </div>
    </fieldset>
}

type Props = {
    mode: DemoMode; onMode: (value: DemoMode) => void
    view: DemoView; onView: (value: DemoView) => void
    ballotSource: BallotSource; onBallot: (value: BallotSource) => void
    startAt: StartAt; onStartAt: (value: StartAt) => void
    busy: 'start' | 'lobby' | null; progress: string[]; error: string
    onStart: () => void; onLobby: () => void
}

export default function DemoSetup({ mode, onMode, view, onView, ballotSource, onBallot, startAt, onStartAt, busy, progress, error, onStart, onLobby }: Props) {
    return <main className="demo-setup demo-setup--choices">
        <header className="demo-setup-header"><button className="demo-link" type="button" onClick={() => { window.location.hash = '/' }}><span aria-hidden="true">←</span> Back home</button><h1 id="demo-title">Judge demo</h1></header>
        <section className="demo-setup-content" aria-labelledby="demo-title">
            <details className="demo-description">
                <summary><span>About the demo</span><span className="demo-description-chevron" aria-hidden="true">⌄</span></summary>
                <div className="demo-description-body">
                    {mode === 'windows' ? <p>Play T01 with <strong>three independent windows</strong>. You are Alex, the CEO and host. Morgan and Sam join from their own windows or devices. Each player takes their own turn, writes their own decision and answers their own coach.</p>
                        : mode === 'solo' ? <p>Play as <strong>Alex, the CEO and host</strong>. Morgan (IT recovery) and Sam (communications) are automated board members with separate test memberships. They play saved clips on their turns and vote after you. In individual decision scenarios such as T01, they write their own decisions.</p>
                            : <p>Control <strong>Alex, Morgan and Sam</strong> in one window. Each has a separate test membership. Their views appear side by side on wide screens; you can switch participants on smaller screens.</p>}
                    <ol className="demo-steps"><li>{mode === 'windows' ? 'Create a room as Alex and share the join links with Morgan and Sam.' : 'Create a room with three test memberships.'}</li><li>Alex is CEO; Morgan handles IT recovery and Sam handles communications.</li><li>Start the T01 Cedar Bridge scenario, or the first available scenario, from its opening briefing.</li></ol>
                    <p>You can switch between the 3D boardroom and call tiles during the game.</p>
                    <details className="demo-recordings"><summary>Saved T01 recordings</summary><ul>{RECORDINGS.map((clip) => <li key={clip.topic}><strong>{clip.topic}</strong> · {clip.seat} · {clip.seconds}s<span>{clip.text}</span></li>)}</ul><p>{mode === 'solo' ? 'Automated members play their own assigned clips. Your own playback and caption submission remain explicit.' : 'Playing a clip never casts a vote. Captions are committed separately as contributions.'}</p></details>
                    <p className="demo-note">Reloading keeps the demo memberships in this browser tab. Reset demo discards them.</p>
                </div>
            </details>
            <div className="demo-selection-groups">
                {/* Two ways in only: this judge demo (solo, automated members) and Host / Join from the home menu. */}
                {MODES.length > 1 && <ChoiceGroup name="demo-mode" title="Mode" value={mode} choices={MODES} onChange={onMode} disabled={Boolean(busy)} />}
                {(mode === 'solo' || mode === 'windows') && <ChoiceGroup name="demo-view" title="Stage" value={view} choices={STAGES} onChange={onView} disabled={Boolean(busy)} />}
                <ChoiceGroup name="ballot-source" title="Voting options" value={ballotSource} choices={BALLOTS} onChange={onBallot} disabled={Boolean(busy)} />
                {mode !== 'windows' && <ChoiceGroup name="start-at" title="Start at" value={startAt} choices={STARTS} onChange={onStartAt} disabled={Boolean(busy)} />}
            </div>
            <div className="demo-setup-actions">
                <button className="demo-primary" type="button" disabled={Boolean(busy)} aria-busy={busy === 'start'} onClick={onStart}>{busy === 'start' ? 'Loading…' : 'Start demo'}<span aria-hidden="true">↗</span></button>
                {mode !== 'windows' && <button className="demo-setup-lobby" type="button" disabled={Boolean(busy)} aria-busy={busy === 'lobby'} onClick={onLobby}>{busy === 'lobby' ? 'Loading…' : 'Open lobby instead'}</button>}
            </div>
            {progress.length > 0 && <ol className="demo-progress" aria-live="polite">{progress.map((text, index) => <li key={index}>{text}</li>)}</ol>}
            {error && <p className="demo-error" role="alert">{error}</p>}
        </section>
    </main>
}
