import test from 'node:test'
import assert from 'node:assert/strict'
import { deferLinkedJoin, linkedJoinKey, roomEntryIntent } from '../src/features/rooms/directEntry.ts'

test('only a valid join link and known name permit direct admission', () => {
    assert.equal(linkedJoinKey('join', ' ab12cd ', 'Known Name'), '["AB12CD","Known Name"]')
    for (const code of ['', '12345', '1234567', 'a!b123']) assert.equal(linkedJoinKey('join', code, 'Known'), null)
    assert.equal(linkedJoinKey('join', 'AB12CD', ''), null)
    assert.equal(linkedJoinKey('join', 'AB12CD', '  '), null)
    assert.equal(linkedJoinKey('host', 'AB12CD', 'Known'), null)
})

test('StrictMode setup cleanup setup dispatches exactly once, with no automatic retry', async () => {
    let calls = 0
    const attempted = new Set<string>()
    const key = linkedJoinKey('join', 'ABC123', 'Guest')
    const firstCleanup = deferLinkedJoin(key, attempted, () => calls++)
    firstCleanup()
    const cleanup = deferLinkedJoin(key, attempted, () => calls++)
    await new Promise((resolve) => setTimeout(resolve, 10))
    assert.equal(calls, 1)
    cleanup()
    deferLinkedJoin(key, attempted, () => calls++)
    await new Promise((resolve) => setTimeout(resolve, 10))
    assert.equal(calls, 1)
})

test('the name prompt can resolve before the first automatic attempt and disposal cancels it', async () => {
    const attempted = new Set<string>()
    let calls = 0
    deferLinkedJoin(linkedJoinKey('join', 'ABC123', ''), attempted, () => calls++)
    await new Promise((resolve) => setTimeout(resolve, 5))
    assert.equal(calls, 0)
    const cleanup = deferLinkedJoin(linkedJoinKey('join', 'ABC123', 'New Name'), attempted, () => calls++)
    cleanup()
    await new Promise((resolve) => setTimeout(resolve, 5))
    assert.equal(calls, 0)
    assert.equal(attempted.size, 0)
})

test('hosting generates a code directly and an uncertain retry preserves both the code and command', () => {
    let calls = 0
    const randomId = () => { calls++; return calls === 1 ? 'command-1' : 'abc12300-0000-4000-8000-000000000000' }
    const intent = roomEntryIntent(null, 'host', 'Alex', 'ignored', '', randomId)
    assert.deepEqual(intent.body, { command_id: 'command-1', room_code: 'ABC123', display_name: 'Alex' })
    assert.equal(roomEntryIntent(intent, 'host', 'Alex', 'changed join input', '', randomId), intent)
    assert.equal(calls, 2)
    assert.equal('role_id' in intent.body, false)
})

test('joining uses the menu code and selected name without generating a replacement room code', () => {
    let calls = 0
    const randomId = () => { calls++; return 'join-command' }
    const intent = roomEntryIntent(null, 'join', 'Guest', ' ab12cd ', '', randomId)
    assert.deepEqual(intent.body, { command_id: 'join-command', room_code: 'AB12CD', display_name: 'Guest' })
    assert.equal(roomEntryIntent(intent, 'join', 'Guest', 'AB12CD', '', randomId), intent)
    assert.equal(calls, 1)
})

test('late role selection and changed names or codes get new command IDs', () => {
    let calls = 0
    const randomId = () => `command-${++calls}`
    const initial = roomEntryIntent(null, 'join', 'Guest', 'ABC123', '', randomId)
    const late = roomEntryIntent(initial, 'join', 'Guest', 'ABC123', 'finance', randomId)
    assert.equal('role_id' in late.body && late.body.role_id, 'finance')
    assert.notEqual(initial.body.command_id, late.body.command_id)
    assert.equal(roomEntryIntent(late, 'join', 'Guest', 'ABC123', 'finance', randomId), late)
    assert.notEqual(roomEntryIntent(late, 'join', 'Renamed', 'ABC123', 'finance', randomId).body.command_id, late.body.command_id)
    assert.notEqual(roomEntryIntent(late, 'join', 'Guest', 'DEF456', 'finance', randomId).body.command_id, late.body.command_id)
})

test('a definitively rejected host code can be regenerated by discarding only that intent', () => {
    let calls = 0
    const randomId = () => (++calls).toString().padStart(6, '0') + '-0000-4000-8000-000000000000'
    const rejected = roomEntryIntent(null, 'host', 'Alex', '', '', randomId)
    const replacement = roomEntryIntent(null, 'host', 'Alex', '', '', randomId)
    assert.notEqual(rejected.body.room_code, replacement.body.room_code)
    assert.notEqual(rejected.body.command_id, replacement.body.command_id)
})
